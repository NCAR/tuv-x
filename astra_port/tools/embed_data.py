#!/usr/bin/env python3
"""Losslessly embed TUV-x data as C99 hexadecimal floating-point constants.

Only regeneration needs Python/numpy/netCDF4 and the reference checkout.
No scientific data are downloaded. --check verifies checked-in generated files.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import math

ROOT = Path(__file__).resolve().parents[1]


def cstring(value):
    return json.dumps(value, ensure_ascii=True)


def oxygen_coefficients(source):
    """Compile the text Chebyshev coefficients without a runtime parser."""
    path = source / "data/cross_sections/O2_parameters.txt"
    lines = path.read_text().splitlines()
    blocks = ["/* Generated by tools/embed_data.py from data/cross_sections/O2_parameters.txt. */\n"]
    for name, start in [("oxygen_a", 2), ("oxygen_b", 24)]:
        rows = [[float(v) for v in line.split(",") if v.strip()] for line in lines[start:start+20]]
        assert len(rows) == 20 and all(len(row) == 17 for row in rows)
        blocks.append(f"static const double {name}[17][20] = {{\n")
        for column in zip(*rows):
            blocks.append("    {\n")
            for i in range(0, 20, 4):
                blocks.append("        " + ", ".join(v.hex() for v in column[i:i+4]) + ",\n")
            blocks.append("    },\n")
        blocks.append("};\n")
    return "".join(blocks)


def generate_catalogue(source, directory="data"):
    """Scientific numeric tables and text; test-only NetCDF I/O fixtures are excluded."""
    from netCDF4 import Dataset
    import numpy as np
    blocks = ["/* Generated by tools/embed_data.py; do not edit. */\n"]
    entries, manifest = [], []
    for index, path in enumerate(sorted((source / directory).rglob("*"))):
        if (not path.is_file() or path.name == "io_netcdf_test_data.nc"
                or "old_tuv" in path.relative_to(source).parts):
            continue
        relative = path.relative_to(source).as_posix()
        raw = path.read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        entry = {"path": relative, "sha256": digest, "bytes": len(raw)}
        prefix = f"tt_data_{index}"
        if path.suffix == ".nc":
            variables = []
            with Dataset(path) as nc:
                nc.set_auto_maskandscale(False)
                for vi, (name, var) in enumerate(nc.variables.items()):
                    values = np.asarray(var[:], dtype=np.float64).ravel()
                    if len(var.shape) > 4:
                        raise ValueError(f"Unsupported rank in {path}:{name}")
                    identifier = f"{prefix}_v{vi}"
                    blocks.append(f"static const double {identifier}[] = {{\n")
                    literals = []
                    for x in values:
                        v = float(x)
                        if not math.isfinite(v):
                            raise ValueError(f"Nonfinite scientific datum in {path}:{name}")
                        literals.append(v.hex())
                    for start in range(0, len(literals), 4):
                        blocks.append("    " + ", ".join(literals[start:start+4]) + ",\n")
                    if not len(values):
                        blocks.append("    0.0,\n")
                    blocks.append("};\n")
                    attrs = {n: (v.tolist() if hasattr(v, "tolist") else v)
                             for n in var.ncattrs() for v in [var.getncattr(n)]}
                    attr_id = identifier + "_attrs"
                    attr_raw = json.dumps(attrs, sort_keys=True).encode("ascii")
                    blocks.append(f"static const char {attr_id}[] = {{\n")
                    for start in range(0, len(attr_raw), 24):
                        blocks.append("    " + ",".join(map(str, attr_raw[start:start+24])) + ",\n")
                    blocks.append("    0\n};\n")
                    shape = list(var.shape) + [0] * (4-len(var.shape))
                    variables.append("    {" + ", ".join([
                        cstring(name), str(len(var.shape)), "{" + ", ".join(map(str, shape)) + "}",
                        str(len(values)), identifier, attr_id]) + "},\n")
                entry["variables"] = {n: list(v.shape) for n, v in nc.variables.items()}
            blocks.append(f"static const tt_data_variable {prefix}[] = {{\n")
            blocks.extend(variables)
            blocks.append("};\n")
            entries.append(f"    {{{cstring(relative)}, {cstring(digest)}, {len(variables)}, {prefix}, NULL, 0}},\n")
        else:
            # Byte initializers avoid implementation limits on string literals
            # and preserve original encodings, line endings and whitespace.
            blocks.append(f"static const char {prefix}[] = {{\n")
            for start in range(0, len(raw), 24):
                blocks.append("    " + ",".join(str(v if v < 128 else v-256) for v in raw[start:start+24]) + ",\n")
            blocks.append("    0\n};\n")
            entries.append(f"    {{{cstring(relative)}, {cstring(digest)}, 0, NULL, {prefix}, {len(raw)}}},\n")
        manifest.append(entry)
    blocks.append("static const tt_dataset tt_catalogue[] = {\n")
    blocks.extend(entries)
    blocks.append("};\n")
    return "".join(blocks), manifest


def generate(source, test_fixtures=False):
    blocks, manifest = generate_catalogue(source, "test/data" if test_fixtures else "data")
    revision = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
    if test_fixtures:
        return {
            ROOT / "tests/generated/data.inc": blocks,
            ROOT / "tests/generated/data_manifest.json": json.dumps(
                {"upstream_revision": revision, "files": manifest}, indent=2) + "\n"
        }
    return {
        ROOT / "src/generated/data.inc": blocks,
        ROOT / "src/generated/oxygen.inc": oxygen_coefficients(source),
        ROOT / "data/manifest.json": json.dumps({"upstream_revision": revision, "files": manifest}, indent=2) + "\n"
    }



def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source", type=Path, default=ROOT.parent / "TUV-x")
    p.add_argument("--check", action="store_true")
    p.add_argument("--test-fixtures", action="store_true", help="Embed original test inputs in the test suite")
    a = p.parse_args()
    for path, text in generate(a.source, a.test_fixtures).items():
        if a.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Out of date: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
