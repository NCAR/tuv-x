#!/usr/bin/env python3
"""Compile profile factory configurations for tests, with source provenance."""
import argparse
import copy
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]


def generate(source):
    cases, provenance = [], []
    default = json.loads((source/'test/data/grid.test.config.json').read_text())
    paths = sorted((source/'test/data').glob('*.json')) + sorted((source/'examples').glob('*.json'))
    for path in paths:
        raw = path.read_text()
        raw = raw.replace('#PHOTO_RATES',(source/'data/photolysis_rate_constants.json').read_text())
        raw = raw.replace('#DOSE_RATES',(source/'data/dose_rates.json').read_text())
        try: config = json.loads(raw)
        except json.JSONDecodeError: continue
        if isinstance(config,dict):
            profiles = config.get('profiles',[])
            grids = config.get('grids',default)
        elif path.name.startswith('profile.'):
            profiles, grids = config, copy.deepcopy(default)
            if path.name == 'profile.simple.config.json':
                grids = json.loads((source/'test/data/grid.simple.config.json').read_text())
            if path.name == 'profile.doug.config.json': grids[0]['ends at']=150
        else: continue
        if not profiles: continue
        origin = path.relative_to(source).as_posix()
        for profile in profiles:
            cases.append((origin,grids,profile))
        provenance.append({'path':origin,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
    for kind, filename in [('air','ussa.dens'),('O2','ussa.dens'),('O3','ussa.ozone')]:
        for top in (40,80,120,160):
            for scale in ((0,4.5,8.01,12.5) if kind != "air" else (None,)):
                grids = [{'name':'height','units':'km','type':'equal interval','begins at':0,
                          'ends at':top,'cell delta':2.5}]
                profile={'name':kind,'units':'molecule cm-3','type':kind,'scale height':scale,
                         'file path':'data/profiles/atmosphere/'+filename}
                if scale is None: del profile['scale height']
                if kind == 'O3': profile['reference column']=250
                cases.append(('additional/gas-profile',grids,profile))
    for zone in (-7,0,5.5):
        for year,month,day in [(1950,1,1),(2000,2,29),(2026,10,18),(2050,12,31)]:
            grids=[{'name':'time','units':'hours','type':'equal interval','begins at':0,
                    'ends at':24,'cell delta':1}]
            for solar in ('solar zenith angle','Earth-Sun distance'):
                profile={'name':solar,'units':'degrees' if solar=='solar zenith angle' else 'AU',
                    'type':solar,'year':year,'month':month,'day':day,'time zone':zone}
                if solar=='solar zenith angle': profile.update({'latitude':38.9072,'longitude':-77.0369})
                cases.append(('additional/solar-profile',grids,profile))
    blocks=['/* Generated by tools/generate_profile_cases.py; do not edit. */\n',
            'static const struct profile_case { int valid; const char *origin, *grids, *config; } profile_cases[] = {\n']
    for origin,grids,config in cases:
        valid = config['type'] != 'solar zenith angle' or ('latitude' in config and 'longitude' in config)
        valid = valid and (config['type'] not in ('from csv file','from config file') or 'grid' in config)
        if any(g['type'] not in ('equal interval','from csv file','from config file') for g in grids): valid=-1
        blocks.append('    {'+', '.join([str(int(valid)),json.dumps(origin),json.dumps(json.dumps(grids,separators=(',',':'))),
                                        json.dumps(json.dumps(config,separators=(',',':')))])+'},\n')
    blocks.append('};\n')
    return ''.join(blocks),json.dumps(provenance,indent=2)+'\n'


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',type=Path,default=ROOT.parent/'TUV-x')
    p.add_argument('--check',action='store_true')
    a=p.parse_args()
    for name,text in zip(('profile_cases.inc','profile_cases_manifest.json'),generate(a.source)):
        path=ROOT/'tests/generated'/name
        if a.check:
            if path.read_text()!=text: raise SystemExit(f'Stale file: {path}')
        else: path.write_text(text)
if __name__=='__main__': main()
