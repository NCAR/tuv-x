#!/usr/bin/env python3
"""Embed whole-model reference scenarios; change only diagnostic output flags."""
import argparse
import copy
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]


def quiet(value):
    if isinstance(value, dict):
        return {k: False if k == 'enable diagnostics' else quiet(v) for k, v in value.items()}
    if isinstance(value, list):
        return [quiet(v) for v in value]
    return value


def generate(source):
    cases, provenance = [], []

    def read(name):
        path = source / name
        raw = path.read_text()
        for marker, fragment in [('#PHOTO_RATES', 'photolysis_rate_constants.json'),
                                 ('#DOSE_RATES', 'dose_rates.json')]:
            raw = raw.replace(marker, (source / 'data' / fragment).read_text())
        provenance.append({'path': name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
        return quiet(json.loads(raw))

    names = ['examples/tuv_5_4.json', 'examples/ts1_tsmlt.json',
             'test/data/photorates.test.config.json', 'test/data/doserates.test.config.json',
             'test/data/solver_from_host.json', 'test/data/solver_from_host.other_solver.json']
    names += [p.relative_to(source).as_posix() for p in sorted((source/'test/data').glob('radiators.*.config.json'))
              if 'from_netcdf' not in p.name]
    for name in names:
        cases.append((name, read(name)))
    heat = read('test/data/heating_rates.json')
    heat['photolysis'] = {'reactions': heat.pop('reactions')}
    heat['O2 absorption'] = {}
    heat['radiative transfer'] = {'cross sections': [], 'radiators': [], 'solver': {'type': 'from host'}}
    cases.append(('additional/heating-with-host-radiation', heat))
    base = copy.deepcopy(cases[0][1])
    base['O2 absorption']['O2 estimate'] = {'scale factor': 0.2095}
    cases.append(('additional/estimated-O2', copy.deepcopy(base)))
    for p in base['profiles']:
        if p['name'] == 'surface albedo': p['uniform value'] = 1.0
        if p['name'] == 'O3': p['reference column'] = 600.0
    cases.append(('additional/high-ozone-bright-surface', copy.deepcopy(base)))
    # Small columns exercise every solver option without repeating large tables.
    base['grids'] = [{'name': 'height', 'units': 'km', 'type': 'from config file',
                     'values': [1.2, 2.7, 6.5, 20.0, 50.0, 100.0]},
                    {'name': 'wavelength', 'units': 'nm', 'type': 'equal interval',
                     'begins at': 300, 'ends at': 800, 'cell delta': 50}]
    base['profiles'] = [p for p in base['profiles'] if p['type'] not in ('solar zenith angle', 'Earth-Sun distance')]
    for streams in (2, 6, 8, 16, 32):
        base['radiative transfer']['solver'] = {'type': 'discrete ordinate', 'number of streams': streams}
        cases.append((f'additional/nonuniform-{streams}-streams', copy.deepcopy(base)))
    base['radiative transfer']['radiators'] = []
    base['radiative transfer']['cross sections'] = []
    for solver in ({'type': 'delta eddington'}, {'type': 'discrete ordinate', 'number of streams': 4}):
        base['radiative transfer']['solver'] = solver
        cases.append(('additional/vacuum-'+solver['type'], copy.deepcopy(base)))
    nc = read('test/data/radiators.from_netcdf_file.config.json')
    base['grids'] = nc['grids']
    # Some action spectra require ultraviolet bins to normalize; this fixture
    # contains only visible wavelengths, so compare its radiation fields.
    base.pop('dose rates', None)
    base.pop('photolysis', None)
    base['radiative transfer']['radiators'] = nc['radiators']
    cases.append(('additional/compiled-radiator', base))
    blocks = ['/* Generated by tools/generate_model_cases.py; do not edit. */\n',
              'static const struct model_case { int runnable; const char *origin, *config, *reference; } model_cases[] = {\n']
    for origin, config in cases:
        reference = None
        transfer = config['radiative transfer']
        if not transfer['radiators'] and transfer['solver']['type'] != 'from host':
            # The reference mixer dereferences radiator(1) for an empty list.
            # One zero-depth absorber has precisely the same floor arithmetic.
            reference = copy.deepcopy(config)
            reference['radiative transfer']['cross sections'].append(
                {'name': 'vacuum', 'type': 'base', 'data': {'default value': 0}})
            reference['radiative transfer']['radiators'].append(
                {'name': 'vacuum', 'type': 'base', 'cross section': 'vacuum',
                 'vertical profile': 'air', 'vertical profile units': 'molecule cm-3'})
        runnable = origin != 'additional/compiled-radiator'
        blocks.append('    {' + str(int(runnable)) + ', ' + json.dumps(origin) + ', ' +
                      json.dumps(json.dumps(config, separators=(',', ':'))) + ', ' +
                      (json.dumps(json.dumps(reference, separators=(',', ':'))) if reference else 'NULL') + '},\n')
    blocks.append('};\n')
    invalid = []
    template = cases[0][1]
    for name in ('height', 'wavelength'):
        cfg = copy.deepcopy(template)
        cfg['grids'] = [g for g in cfg['grids'] if g['name'] != name]
        invalid.append(cfg)
    for name in ('temperature', 'air', 'O2', 'surface albedo', 'extraterrestrial flux'):
        cfg = copy.deepcopy(template)
        cfg['profiles'] = [p for p in cfg['profiles'] if p['name'] != name]
        invalid.append(cfg)
    for solver in ({'type': 'unknown'}, {'type': 'discrete ordinate', 'number of streams': 3},
                   {'type': 'discrete ordinate', 'number of streams': 34}):
        cfg = copy.deepcopy(template)
        cfg['radiative transfer']['solver'] = solver
        invalid.append(cfg)
    for key, value in [('type', 'unknown'), ('vertical profile', 'absent'), ('cross section', 'absent')]:
        cfg = copy.deepcopy(template)
        cfg['radiative transfer']['radiators'][0][key] = value
        invalid.append(cfg)
    for oxygen in ({'O2 estimate': {'scale factor': -1}}, {'cross section parameters file': 'absent'}):
        cfg = copy.deepcopy(template)
        cfg['O2 absorption'] = oxygen
        invalid.append(cfg)
    cfg = copy.deepcopy(template)
    cfg['photolysis']['reactions'][0]['heating'] = {'energy term': -1}
    invalid.append(cfg)
    cfg = copy.deepcopy(template)
    cfg['photolysis']['reactions'][0]['quantum yield']['type'] = 'unknown'
    invalid.append(cfg)
    blocks.append('static const char *const invalid_model_cases[] = {\n')
    for config in invalid:
        blocks.append('    ' + json.dumps(json.dumps(config, separators=(',', ':'))) + ',\n')
    blocks.append('};\n')
    hosts=['/* Generated by tools/generate_model_cases.py; do not edit. */\n',
           'static const char *const host_model_cases[] = {\n']
    for i in range(4):
        config=copy.deepcopy(cases[i if i<2 else 0][1])
        config['grids']=[g for g in config['grids'] if g['name'] not in ('height','wavelength')]
        config['profiles']=[p for p in config['profiles'] if p['name'] not in ('air','temperature')]
        if i>=2:
            config['radiative transfer']['solver']={'type':'discrete ordinate','number of streams':2 if i==2 else 8}
        hosts.append('    '+json.dumps(json.dumps(config,separators=(',',':')))+',\n')
    hosts.append('};\n')
    return ''.join(blocks), json.dumps(provenance, indent=2)+'\n', ''.join(hosts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT.parent/'TUV-x')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in zip(('model_cases.inc', 'model_cases_manifest.json', 'host_model_cases.inc'), generate(args.source)):
        path = ROOT/'tests/generated'/name
        if args.check:
            if path.read_text() != text: raise SystemExit(f'Stale file: {path}')
        else: path.write_text(text)
if __name__ == '__main__': main()
