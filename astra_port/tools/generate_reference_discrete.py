#!/usr/bin/env python3
"""Extract private Fortran helpers verbatim for independent direct testing.

The original library exposes only PSNDO. This test-only module preserves the
private routines' source text and records its hash, without changing visibility
or code in the original checkout or library.
"""
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
source = ROOT.parent / "TUV-x/src/radiative_transfer/solvers/discrete_ordinant_util.F90"
original = source.read_text()
text = f"""! Generated by tools/generate_reference_discrete.py. Test code only.
! Original source SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}
! Copyright (C) 2020-2026 University Corporation for Atmospheric Research
! SPDX-License-Identifier: Apache-2.0
module reference_discrete_helpers
  use iso_c_binding
  use musica_constants, only: dk => musica_dk
  implicit none
  real(dk), parameter :: rZERO=0.0_dk,ONEHALF=0.5_dk,rONE=1.0_dk
  real(dk), parameter :: rTWO=2.0_dk,rFOUR=4.0_dk,rTEN=10.0_dk
  integer, parameter :: MAXSQT=1000
  type :: solver_constants_t
    real(dk) :: SQT(MAXSQT)
  end type
contains
  subroutine ref_eigen(n,a,values,vectors,info) bind(c)
    integer(c_int), value :: n
    real(c_double), intent(in) :: a(n,n)
    real(c_double), intent(out) :: values(n),vectors(n,n)
    integer(c_int), intent(out) :: info
    real(c_double) :: work(2*n),aa(n,n),vv(n,n),ee(n)
    call ASYMTX(a,vectors,values,info,work,aa,vv,ee)
  end subroutine
  subroutine ref_quadrature(n,nodes,weights) bind(c)
    integer(c_int), value :: n
    real(c_double), intent(out) :: nodes(n),weights(n)
    call QGAUSN(n,nodes,weights)
  end subroutine
  subroutine ref_legendre(degree,n,mu,poly) bind(c)
    integer(c_int), value :: degree,n
    real(c_double), intent(in) :: mu(n)
    real(c_double), intent(out) :: poly(0:degree,n)
    type(solver_constants_t) :: constants
    call LEPOLY(n,0,degree,mu,poly,constants)
  end subroutine
"""
for name in ["ASYMTX", "QGAUSN", "LEPOLY", "ErrMsg"]:
    match = re.search(r"(?ims)^\s*SUBROUTINE\s+" + name + r"\(.*?^\s*END SUBROUTINE\s+" + name, original)
    if match is None:
        raise RuntimeError(f"Missing original helper {name}")
    text += match[0] + "\n"
text += "end module\n"
path = ROOT / "tests/generated/reference_discrete_helpers.F90"
path.write_text(text)
print(path.relative_to(ROOT))
